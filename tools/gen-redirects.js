/* Writes _redirects: a permanent 301 from every published page's no-slash URL
   (/2mm-graph-paper) to its canonical trailing-slash URL (/2mm-graph-paper/).

   Without this, Cloudflare's default html_handling answers /foo with a 307
   (temporary) redirect, and Google has shown those no-slash variants in search.
   Re-run after adding or removing a page: npm run gen:redirects */
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const SKIP = new Set(['node_modules', 'worker', 'tools', 'assets', 'artifacts', '.git', '.wrangler']);

const slugs = fs.readdirSync(ROOT, { withFileTypes: true })
  .filter(d => d.isDirectory() && !SKIP.has(d.name) && !d.name.startsWith('.'))
  .filter(d => fs.existsSync(path.join(ROOT, d.name, 'index.html')))
  .map(d => d.name)
  .sort();

const lines = [
  '# Generated by tools/gen-redirects.js. Do not edit by hand.',
  '# Canonical page URLs end with a slash; send the no-slash form there permanently.',
  ...slugs.map(s => `/${s} /${s}/ 301`)
];
fs.writeFileSync(path.join(ROOT, '_redirects'), lines.join('\n') + '\n');
console.log(`Wrote _redirects with ${slugs.length} rules.`);
